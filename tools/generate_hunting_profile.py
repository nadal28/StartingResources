"""Generate relocation/unwind metadata for the exact-build native hunting copy.

Requires pefile and capstone. Run only after analysing a new supported build.
The executable is read-only; the generated header is reviewed and committed.
"""
import argparse
import hashlib
from pathlib import Path
import struct

import pefile
from capstone import Cs, CS_ARCH_X86, CS_MODE_64, CS_GRP_JUMP, CS_GRP_CALL
from capstone.x86_const import X86_OP_MEM, X86_OP_IMM, X86_REG_RIP

from low_priority import enable
from build_native import verify

ROOT = Path(__file__).resolve().parents[1]
BEGIN, END, CODE_END = 0x4ddf0b0, 0x4ddff32, 0x4ddfef4


def generate(executable):
    verify(executable)
    pe = pefile.PE(str(executable), fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXCEPTION']])
    base = pe.OPTIONAL_HEADER.ImageBase
    code = pe.get_data(BEGIN, END - BEGIN)
    dis = Cs(CS_ARCH_X86, CS_MODE_64)
    dis.detail = True
    fixups = []
    for ins in dis.disasm(code[:CODE_END - BEGIN], base + BEGIN):
        for operand in ins.operands:
            if operand.type == X86_OP_MEM and operand.mem.base == X86_REG_RIP:
                target = ins.address + ins.size + operand.mem.disp - base
                # The two image-base LEAs intentionally become the copy's
                # synthetic image base: its original RVA jump tables still work.
                if target == 0 or BEGIN <= target < END:
                    continue
                assert ins.disp_size == 4
                fixups.append((ins.address - base - BEGIN + ins.disp_offset,
                               ins.address - base - BEGIN + ins.size, target))
        if (ins.group(CS_GRP_JUMP) or ins.group(CS_GRP_CALL)) and ins.operands[0].type == X86_OP_IMM:
            target = ins.operands[0].imm - base
            if not BEGIN <= target < END:
                assert ins.imm_size == 4
                fixups.append((ins.address - base - BEGIN + ins.imm_offset,
                               ins.address - base - BEGIN + ins.size, target))

    entries, unwind, chains = [], bytearray(), []
    ranges = [entry.struct for entry in pe.DIRECTORY_ENTRY_EXCEPTION
              if BEGIN <= entry.struct.BeginAddress < END]
    offsets = {}
    for entry in ranges:
        rva = entry.UnwindData
        if rva not in offsets:
            offsets[rva] = len(unwind)
            head = pe.get_data(rva, 4)
            flags, count = head[0] >> 3, head[2]
            assert flags in (0, 4), 'Exception handlers need separate analysis'
            size = 4 + 2 * ((count + 1) & ~1)
            if flags == 4:
                chains.append(len(unwind) + size)
                size += 12
            unwind.extend(pe.get_data(rva, size))
        entries.append((entry.BeginAddress - BEGIN, entry.EndAddress - BEGIN, offsets[rva]))
    for offset in chains:
        begin, end, info = struct.unpack_from('<III', unwind, offset)
        assert BEGIN <= begin < end <= END and info in offsets
        struct.pack_into('<III', unwind, offset, begin - BEGIN, end - BEGIN, offsets[info])

    def array(name, data):
        return 'static const unsigned char ' + name + '[]={\n' + '\n'.join(
            '    ' + ','.join(f'0x{x:02x}' for x in data[i:i + 24]) + ','
            for i in range(0, len(data), 24)) + '\n};\n'

    header = '/* Generated by tools/generate_hunting_profile.py; exact-build data. */\n'
    header += f'#define HUNTING_RVA 0x{BEGIN:x}u\n#define HUNTING_SIZE {len(code)}u\n'
    # Copy code from the user's verified installation at runtime. Only its
    # fingerprint and relocation facts belong in the distributed profile.
    header += '#define HUNTING_SHA256_BYTES {' + ','.join(
        f'0x{x:02x}' for x in hashlib.sha256(code).digest()) + '}\n'
    header += 'typedef struct {unsigned offset,next,target;} HuntFixup;\n'
    header += 'static const HuntFixup hunting_fixups[]={\n' + ''.join(
        '    {%d,%d,0x%x},\n' % item for item in fixups) + '};\n'
    header += array('hunting_unwind', unwind)
    header += 'static const RUNTIME_FUNCTION hunting_ranges[]={' + ','.join(
        '{%d,%d,%d}' % item for item in entries) + '};\n'
    header += 'static const unsigned hunting_chains[]={' + ','.join(map(str, chains)) + '};\n'
    target = ROOT / 'native/deer_hunting_build.h'
    target.write_text(header, encoding='ascii')
    print(f'{target.name}: {len(code)} code bytes, {len(fixups)} relocations, {len(entries)} unwind ranges')


if __name__ == '__main__':
    enable()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--exe', required=True, type=Path)
    generate(parser.parse_args().exe)
